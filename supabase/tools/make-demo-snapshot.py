#!/usr/bin/env python3
"""Writes the migration that stores the demo's opening snapshot (D59) from demo/seed.json.

The live database was imported from the same seed on 10/11/2026 and then used for the stage 6
checks, so its rows no longer show the office as it was on Monday 9/11/2026 at 19:30. The
migration copies the current rows into the snapshot schema and then puts back, from the seed,
every field that the checks could have changed: request and document states, and which files
were marked unreadable. Rows added after the import (uploads, messages, log entries with a later
time) stay out of the snapshot. Only fictional data; no tokens, emails or Drive ids.

    python3 supabase/tools/make-demo-snapshot.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SEED = ROOT / 'demo' / 'seed.json'
OUT = ROOT / 'supabase' / 'migrations' / '20261119200100_nelio_demo_snapshot.sql'


def t(value):
    return value or None


def main():
    seed = json.loads(SEED.read_text(encoding='utf-8'))
    requests = [[r['request_id'], r['status'], int(r['reminder_count'] or 0), t(r['last_reminder_at']),
                 r['last_activity'], t(r['last_activity_at']), r['client_note'], t(r['submitted_at']),
                 t(r['completed_at']), r['completed_by'], r['completion_note']] for r in seed['requests']]
    items = [[i['item_id'], i['status'], int(i['file_count'] or 0), i['na_note'], i['reject_reason'],
              t(i['updated_at']), i['updated_by'], int(i['last_seq'] or 0)] for i in seed['items']]
    uploads = [[u['upload_id'], u['status']] for u in seed['uploads']]
    cycles = [[c['cycle_id'], t(c['reminder1_sent_at']), t(c['reminder2_sent_at']), t(c['last_day_sent_at']),
               t(c['call_list_sent_at']), t(c['summary_sent_at']), c['status'], t(c['closed_at'])] for c in seed['cycles']]
    dump = lambda rows: json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
    for rows in (requests, items, uploads, cycles):
        assert '$seed$' not in dump(rows)
    sql = f"""-- Nelio 0.9.0: the demo's opening snapshot (D59), Monday 9/11/2026, 19:30.
-- Generated by supabase/tools/make-demo-snapshot.py from demo/seed.json ({seed['seed_id']}). Do not edit by hand.
-- "אפס את הדמו" (nelio_demo_reset) copies these rows back. Clients, links, settings and templates are not here.

insert into nelio_demo.cycles select * from public.cycles;
insert into nelio_demo.requests select * from public.requests;
insert into nelio_demo.items select * from public.items;
insert into nelio_demo.uploads select * from public.uploads where uploaded_at <= '{seed['snapshot']}';
insert into nelio_demo.messages select * from public.messages where created_at <= '{seed['snapshot']}';
insert into nelio_demo.activity_log select * from public.activity_log where at <= '{seed['snapshot']}';

update nelio_demo.cycles c set reminder1_sent_at = s.r1::timestamptz, reminder2_sent_at = s.r2::timestamptz,
 last_day_sent_at = s.ld::timestamptz, call_list_sent_at = s.cl::timestamptz, summary_sent_at = s.su::timestamptz,
 status = s.st, closed_at = s.ca::timestamptz
from (select x->>0 id, x->>1 r1, x->>2 r2, x->>3 ld, x->>4 cl, x->>5 su, x->>6 st, x->>7 ca
 from jsonb_array_elements($seed${dump(cycles)}$seed$::jsonb) x) s
where c.cycle_id = s.id;

update nelio_demo.requests r set status = s.st, reminder_count = s.rc, last_reminder_at = s.lr::timestamptz,
 last_activity = s.la, last_activity_at = s.laa::timestamptz, client_note = s.cn, submitted_at = s.sa::timestamptz,
 completed_at = s.ca::timestamptz, completed_by = s.cb, completion_note = s.cno
from (select x->>0 id, x->>1 st, (x->>2)::bigint rc, x->>3 lr, x->>4 la, x->>5 laa, x->>6 cn, x->>7 sa, x->>8 ca, x->>9 cb, x->>10 cno
 from jsonb_array_elements($seed${dump(requests)}$seed$::jsonb) x) s
where r.request_id = s.id;

update nelio_demo.items i set status = s.st, file_count = s.fc, na_note = s.nn, reject_reason = s.rr,
 updated_at = s.ua::timestamptz, updated_by = s.ub, last_seq = s.ls
from (select x->>0 id, x->>1 st, (x->>2)::bigint fc, x->>3 nn, x->>4 rr, x->>5 ua, x->>6 ub, (x->>7)::bigint ls
 from jsonb_array_elements($seed${dump(items)}$seed$::jsonb) x) s
where i.item_id = s.id;

update nelio_demo.uploads u set status = s.st
from (select x->>0 id, x->>1 st from jsonb_array_elements($seed${dump(uploads)}$seed$::jsonb) x) s
where u.upload_id = s.id;
"""
    OUT.write_text(sql, encoding='utf-8')
    print(OUT.relative_to(ROOT), len(sql), 'bytes')


if __name__ == '__main__':
    main()
